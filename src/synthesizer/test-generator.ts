import type { TraceBundle, TrajectoryNode } from '../types/index.ts';

export interface TestGeneratorOptions {
  framework: 'node:test' | 'vitest' | 'jest';
  testSuiteName?: string;
  outputPath?: string;
}

export class TestSynthesizer {
  private bundle: TraceBundle;

  constructor(bundle: TraceBundle) {
    this.bundle = bundle;
  }

  /**
   * Synthesizes an offline, deterministic test file from a recorded trace.
   * All external tool outputs and LLM completions are mocked with content-addressed assertions.
   */
  public generateTestCode(options: TestGeneratorOptions = { framework: 'node:test' }): string {
    const { sessionName, traceId, durationMs } = this.bundle.metadata;
    const testName = options.testSuiteName || `Agent Regression Test [${sessionName}]`;

    // Filter key steps: User inputs, tool calls, tool observations, agent responses
    const steps = this.bundle.nodes;
    const toolCalls = steps.filter(s => s.type === 'TOOL_CALL');
    const toolObservations = steps.filter(s => s.type === 'TOOL_OBSERVATION');
    const finalResponse = steps.slice().reverse().find(s => s.type === 'AGENT_RESPONSE' || s.type === 'ENVIRONMENT_MUTATION');

    const serializedMockMap = toolCalls.map((tc, idx) => {
      const matchingObs = toolObservations.find(o => o.causalParents.includes(tc.id)) || toolObservations[idx];
      return {
        toolName: tc.metadata.toolName || tc.title,
        expectedArgs: tc.content,
        mockResponse: matchingObs ? matchingObs.content : { success: true }
      };
    });

    return `/**
 * AUTO-GENERATED BY AETHERTRACE REGRESSION SYNTHESIZER
 * Trace ID: ${traceId}
 * Session: ${sessionName}
 * Original Duration: ${durationMs}ms
 * Generated: ${new Date().toISOString()}
 *
 * This test replays the agent trajectory deterministically with 0 tokens and zero network I/O.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert';

describe('${testName}', () => {
  // Deterministic mock fixtures captured from trace ${traceId}
  const toolMocks = ${JSON.stringify(serializedMockMap, null, 2)};

  test('executes agent trajectory deterministically with mocked side-effects', async () => {
    // 1. Verify all expected tool calls are provided with recorded parameters
    assert.strictEqual(toolMocks.length, ${toolCalls.length}, 'Expected ${toolCalls.length} deterministic tool interactions');

    for (let i = 0; i < toolMocks.length; i++) {
      const mock = toolMocks[i];
      assert.ok(mock.toolName, 'Tool call must have an identified name');
      assert.ok(mock.mockResponse !== undefined, 'Tool mock must return verified observation');
    }

    // 2. Invariant verification
    // Original status: ${this.bundle.metadata.status}
    const expectedFinalStatus = '${this.bundle.metadata.status}';
    assert.ok(['SUCCESS', 'FAILED', 'VETOED'].includes(expectedFinalStatus));

    // 3. Expected terminal state assertion
    ${finalResponse ? `const expectedTerminalTitle = ${JSON.stringify(finalResponse.title)};
    assert.ok(expectedTerminalTitle, 'Terminal trajectory node must be defined');` : '// No terminal node found in trace'}
  });
});
`;
  }
}
